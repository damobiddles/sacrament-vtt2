// Packs private/builder.html into a function module so the page is only ever served by the password gate.
// Netlify runs this before bundling functions (see netlify.toml). The output is not committed.
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(new URL('../private/builder.html', import.meta.url), 'utf8');
const out = new URL('../netlify/functions/builder-page.mjs', import.meta.url);
writeFileSync(out, '// Generated by scripts/build-private.mjs. Do not edit.\nexport default ' + JSON.stringify(html) + ';\n');
console.log('Packed private/builder.html (' + html.length + ' bytes) into the builder function.');
